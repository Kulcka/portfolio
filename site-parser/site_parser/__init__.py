"""Парсер сайтов по YAML-конфигу с выгрузкой в CSV, Excel и Google Sheets.

Модули:

* ``config``     — загрузка и проверка YAML-конфига;
* ``fetcher``    — сетевой слой: повторы, паузы, User-Agent, robots.txt, кэш;
* ``extract``    — извлечение полей по CSS-селекторам;
* ``converters`` — приведение типов (число, цена, валюта, наличие, ссылка);
* ``scraper``    — обход каталога: пагинация, карточки товаров;
* ``storage``    — SQLite с результатами прошлых прогонов;
* ``diff``       — сравнение прогонов: новые, изменилась цена, пропали;
* ``exporters``  — CSV, XLSX, JSON; ``gsheets`` — Google Sheets;
* ``notify``     — уведомление в Telegram;
* ``pipeline``   — весь прогон целиком; ``cli`` — командная строка.
"""

