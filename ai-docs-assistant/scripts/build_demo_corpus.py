def _font_path() -> Path:
    candidates = [
        os.environ.get("CORPUS_FONT", ""),
        r"C:\Windows\Fonts\arial.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/dejavu/DejaVuSans.ttf",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            return Path(candidate)
    raise SystemExit("Не найден шрифт с кириллицей: задайте путь в переменной CORPUS_FONT")


def build_pdf(path: Path, title: str, pages: list[tuple[str, list[str]]]) -> None:
    from fpdf import FPDF

    pdf = FPDF(format="A4")
    pdf.set_title(title)
    pdf.set_author(COMPANY)
    pdf.set_creation_date(__import__("datetime").datetime(2026, 9, 1))
    pdf.add_font("Main", "", str(_font_path()))
    pdf.set_margins(20, 20, 20)
    pdf.set_auto_page_break(auto=True, margin=20)
    for number, (heading, paragraphs) in enumerate(pages, start=1):
        pdf.add_page()
        pdf.set_font("Main", size=9)
        pdf.cell(0, 6, f"{COMPANY} · {title}", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)
        pdf.set_font("Main", size=15)
        pdf.multi_cell(0, 8, heading, new_x="LMARGIN", new_y="NEXT")
        pdf.ln(3)
        pdf.set_font("Main", size=11)
        for paragraph in paragraphs:
            pdf.multi_cell(0, 6, paragraph, new_x="LMARGIN", new_y="NEXT")
            pdf.ln(2)
        pdf.set_auto_page_break(auto=False)  # подвал в нижнем поле не должен открывать новую страницу
        pdf.set_y(-15)
        pdf.set_font("Main", size=9)
        pdf.cell(0, 6, f"Страница {number} из {len(pages)}", align="C")
        pdf.set_auto_page_break(auto=True, margin=20)
    pdf.output(str(path))


def build_docx(
    path: Path,
    title: str,
    sections: list[tuple[str, list[str]]],
    table: list[tuple[str, ...]] | None = None,
    table_heading: str | None = None,
) -> None:
    import docx

    document = docx.Document()
    document.core_properties.title = title
    document.core_properties.author = COMPANY
    document.add_heading(title, level=0)
    document.add_paragraph(f"{COMPANY}. Редакция от 1 сентября 2026 года.")
    for heading, paragraphs in sections:
        document.add_heading(heading, level=1)
        for paragraph in paragraphs:
            document.add_paragraph(paragraph)
    if table:
        document.add_heading(table_heading or "Сводная таблица", level=1)
        grid = document.add_table(rows=len(table), cols=len(table[0]))
        grid.style = "Table Grid"
        for r, row in enumerate(table):
            for c, value in enumerate(row):
                grid.cell(r, c).text = value
    document.save(str(path))


